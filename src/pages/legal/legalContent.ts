export const LEGAL_CONTENT: Record<LegalLang, DocsByLang> = {
    ru: withDocumentMeta(ru, 'ru'),
    en: withDocumentMeta(en, 'en'),
    ka: withDocumentMeta(ka, 'ka'),
};

export function legalDocPath(id: LegalDocId, lang?: LegalLang): string {
    return lang ? `/${lang}/${id}` : `/${id}`;
}

export function isLegalPath(pathname: string): boolean {
    return /^\/(?:(?:ru|en|ka)\/)?(legal|terms|privacy|returns|refunds|contact|support)\/?$/.test(pathname || '');
}

export function resolveLegalDocId(pathname: string, hash = ''): LegalDocId {
    const last = (pathname || '').replace(/\/+$/, '').split('/').pop()?.toLowerCase() || '';
    if (last === 'privacy') return 'privacy';
    if (last === 'returns' || last === 'refunds') return 'returns';
    if (last === 'terms' || last === 'contact' || last === 'support') return 'terms';

    const h = (hash || '').replace(/^#/, '').toLowerCase();
    if (!h || h === 'terms') return 'terms';
    if (h === 'privacy' || h.startsWith('p-')) return 'privacy';
    if (h === 'returns' || h === 'refunds' || h.startsWith('r-')) return 'returns';
    if (h.startsWith('t-')) return 'terms';
    if (['general', 'registration', 'ordering', 'payment', 'liability', 'personal-data', 'prohibited', 'intellectual-property', 'force-majeure', 'disputes', 'final'].includes(h)) {
        return 'terms';
    }
    return 'terms';
}

export function getLegalDoc(lang: string, docId: LegalDocId): LegalDoc {
    const pack = LEGAL_CONTENT[(lang as LegalLang)] || LEGAL_CONTENT.ru;
    return pack[docId] || pack.terms;
}
