const META_SECTION_ID: Record<LegalDocId, string> = {
    terms: 't-meta',
    privacy: 'p-meta',
    returns: 'r-meta',
};

function withDocumentMeta(pack: DocsByLang, lang: LegalLang): DocsByLang {
    const meta = META_BY_LANG[lang];
    const next = { ...pack };
    (['terms', 'privacy', 'returns'] as LegalDocId[]).forEach((docId) => {
        next[docId] = {
            ...next[docId],
            sections: [
                ...next[docId].sections,
                {
                    id: META_SECTION_ID[docId],
                    title: meta.title,
                    paragraphs: [meta.firstPublished, meta.currentRevision, meta.version],
                },
            ],
        };
    });
    return next;
}

